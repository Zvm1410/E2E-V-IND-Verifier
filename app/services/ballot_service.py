    def export_board(self, filename: str = "board.json") -> None:
        """Write the bulletin-board dict to canonical JSON on disk.

        The digest and multisignature are added by the runner
        (``run_election.py``) after the tally transcript is appended;
        for the in-UI export path this simply writes the current state.
        """
        bb.write_board(self.board, filename)

