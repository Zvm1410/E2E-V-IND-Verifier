    @staticmethod
    def build_receipt_code(artifacts: BallotArtifacts) -> str:
        """Short 16-char code shown on the receipt screen (SPEC section 14
        does not mandate this; it is a UI aid). Uses only public data."""
        sp = artifacts.sum_proof
        base = f"{artifacts.serial}:{sp['c'][:32]}".encode("utf-8")
        return hashlib.sha256(base).hexdigest()[:16].upper()

    # ------------------------------------------------------------------
    # Backwards-compat view: ``board_records`` (Basket A scripts)
    # ------------------------------------------------------------------
    #
    # Every Basket A smoke script scans a flat list ``svc.board_records``
    # and filters by ``record_type``. That was the stub-era shape. In
    # the integrated build the source of truth is the SPEC section 14
    # board dict ``self.board``, mutated by ``board.board.append_*``.
    #
    # This property reconstructs the flat view on demand so those
    # scripts keep working without editing any of them. It is
    # deliberately a view: writing to it does not affect the board.

    @property
    def board_records(self) -> List[Dict[str, Any]]:
        recs: List[Dict[str, Any]] = []

        # 1. Pre-poll section: one commitment record per serial + one
        #    schedule-commitment record. The A scripts filter these by
        #    the ``record_type`` labels ``pre_poll_commitment`` and
        #    ``test_schedule_commitment``.
        prepoll = self.board.get("prepoll") or {}
        if isinstance(prepoll, dict) and prepoll:
            for entry in prepoll.get("randomness_commitments", []) or []:
                recs.append({
                    "record_type": "pre_poll_commitment",
                    "booth_id": self.config.booth_id,
                    "serial": entry.get("ballot_serial"),
                    "m": self.config.candidate_count,
                    "commitment": entry.get("commitment"),
                })
            sched = prepoll.get("test_schedule_commitment")
            if sched:
                recs.append({
                    "record_type": "test_schedule_commitment",
                    "booth_id": self.config.booth_id,
                    "commitment": sched,
                    "m": self.config.candidate_count,
                })

        # 2. Ballots (in serial order, which is how C stores them).
        for b in self.board.get("ballots", []):
            serial = b.get("ballot_serial")
            recs.append({
                "record_type": "ballot",
                "booth_id": b.get("booth_id", self.config.booth_id),
                "ballot_serial": serial,
                "ciphertext_count": len(b.get("ciphertexts", [])),
                "ciphertexts": b.get("ciphertexts", []),
                "validity_proofs": b.get("validity_proofs", []),
                "sum_proof": b.get("sum_proof", {}),
                # DEBUG-ONLY: candidate_index is what was actually
                # encrypted, tracked in a private map. Not part of the
                # SPEC section 14 ballot record and NOT written to
                # ``self.board`` or ``board.json``.
                "candidate_index":
                    self._encrypted_index_by_serial.get(serial),
            })

        # 3. Spoils.
        for s in self.board.get("spoils", []):
            recs.append({
                "record_type": "spoil",
                "booth_id": s.get("booth_id", self.config.booth_id),
                "ballot_serial": s.get("ballot_serial"),
                "opened_candidate_index": s.get("opened_candidate_index"),
                "randomness": s.get("randomness", []),
                "nonce": s.get("nonce"),
                "verified": s.get("verified"),
            })

        # 4. Schedule opening (revealed seed).
        so = self.board.get("schedule_opening") or {}
        if isinstance(so, dict) and so.get("schedule_seed"):
            recs.append({
                "record_type": "reveal_schedule",
                "booth_id": self.config.booth_id,
                "schedule_seed": so.get("schedule_seed"),
                "schedule_commitment": self.schedule_commitment,
            })

        # 5. Poll register.
        reg = self.board.get("poll_register") or {}
        if isinstance(reg, dict) and reg:
            recs.append({
                "record_type": "register",
                "booth_id": reg.get("booth_id", self.config.booth_id),
                "ballots_issued": reg.get("ballots_issued"),
                "ballots_spoiled": reg.get("ballots_spoiled"),
                "ballots_counted": reg.get("ballots_counted"),
                # No signature until run_election.py adds the multisig
                # over the whole board digest; A's scripts only assert
                # its presence when this field is not None.
                "register_signature": reg.get("register_signature"),
            })

        return recs

    # ------------------------------------------------------------------
    # Convenience for tally stage
    # ------------------------------------------------------------------

    def valid_ballots_ciphertexts(self) -> List[List[ElGamalCiphertext]]:
        """Return the per-candidate ciphertext column of every non-spoiled ballot.

        ``result[i]`` is the list of ``Ciphertext`` objects at candidate
        index ``i`` across all counted ballots. Fed straight into
        ``tally.threshold.aggregate_ciphertexts`` per candidate.
        """
        spoiled = {
            s["ballot_serial"] for s in self.board.get("spoils", [])
        }
        m = self.config.candidate_count
        columns: List[List[ElGamalCiphertext]] = [[] for _ in range(m)]
        for ballot in self.board.get("ballots", []):
            if ballot["ballot_serial"] in spoiled:
                continue
            for ct in ballot["ciphertexts"]:
                i = ct["candidate_index"]
                columns[i].append(
                    ElGamalCiphertext(
                        alpha=int(ct["alpha"], 16),
                        beta=int(ct["beta"], 16),
                    )
                )
        return columns


