class BallotService:
    """A's ballot pipeline, wired through the real Basket B and Basket C.

    The service owns:

    * the pre-poll randomness vectors (integer, secret) and their
      commitments (public, published pre-poll);
    * the test schedule seed and its commitment;
    * the bulletin-board dict that Basket C's board.py functions mutate;
    * the trusted-dealer output (pk, trustee shares, commitments);
    * the officer/agent Ed25519 keys.

    None of that math is implemented here. Everything is delegated.
    """

    def __init__(self, config: ElectionConfig, poll_state: PollState):
        self.config = config
        self.poll_state = poll_state
        self.attack_config = AttackConfig()
        self.private_log = PrivateAttackLog()
        self.last_artifacts: Optional[BallotArtifacts] = None

        # A9 stuffing may only fire once per election run.
        self._stuffing_done: bool = False

        # DEBUG-ONLY view: per-serial map of the candidate index that
        # was actually encrypted. Used by ``board_records`` (A's
        # diagnostic projection) so scripts can assert what went into
        # a ballot. NEVER written to ``self.board`` and NEVER exported;
        # the SPEC section 14 ballot record contains only ciphertexts
        # and proofs, as the ElGamal secrecy requires.
        self._encrypted_index_by_serial: Dict[int, int] = {}

        # ---- pre-poll randomness state ---------------------------------
        # Public: per-serial commitments (SHA-256 hex) and schedule commit.
        self.pre_poll_commitments: Dict[int, str] = {}
        self.schedule_commitment: Optional[str] = None
        # Publicly revealed at poll close (empty until then).
        self.schedule_seed: Optional[str] = None
        # Public HEX384 display forms of the randomness vectors, used by
        # the admin screen and by the spoil record.
        self.pre_poll_randomness: Dict[int, List[str]] = {}
        self.pre_poll_nonces: Dict[int, str] = {}
        # SECRET integer form of the randomness vectors, used by Basket B's
        # encrypt_and_prove. Never written to the board, never exported.
        self._r_int: Dict[int, List[int]] = {}
        # Deterministic test schedule (set of scheduled test serials).
        self.scheduled_tests: set[int] = set()

        # ---- election setup: trusted dealer + authorities + base hash --
        self.trustee_setup: TrusteeSetup = run_dealer(
            n=config.trustees_n,
            t=config.trustees_t,
            seed=config.seed,
        )
        # Basket C's initialize_authority_keys uses `cryptography` and its
        # own OS RNG - Ed25519 signing is not part of the deterministic
        # replay surface.
        self.authority_keys, self._authority_privates = initialize_authority_keys(
            number_of_agents=config.agents,
            k=config.agent_k,
        )
        # Officer public bytes for base hash (SPEC section 5.2 wants the
        # 32 RAW bytes of the Ed25519 public key, not the hex form).
        from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
        officer_pub_bytes = self._authority_privates["officer"].public_key().public_bytes(
            encoding=Encoding.Raw, format=PublicFormat.Raw
        )
        agent_pub_bytes = [
            priv.public_key().public_bytes(encoding=Encoding.Raw, format=PublicFormat.Raw)
            for priv in self._authority_privates["agents"]
        ]

        # ---- Base hash Q (SPEC section 5.2), 32 raw bytes --------------
        # Every challenge preimage in the system binds this Q. Computing
        # it once here and reusing it is the ``B4b`` interface promised to
        # A and C at day 2 (handbook).
        self.Q: bytes = compute_base_hash(
            p=p_mod, q=q_ord, g=g_gen,
            election_id=config.election_id,
            candidate_ids=[c.candidate_id for c in config.candidates],
            n=config.trustees_n,
            t=config.trustees_t,
            pk=self.trustee_setup.pk,
            trustee_commitments=[
                self.trustee_setup.commitments[j]
                for j in sorted(self.trustee_setup.commitments)
            ],
            num_agents=config.agents,
            k=config.agent_k,
            officer_pubkey=officer_pub_bytes,
            agent_pubkeys=agent_pub_bytes,
        )

        # ---- The bulletin-board dict (mutated in place) ---------------
        self.board: Dict[str, Any] = _empty_board()
        self.board["election_config"] = {
            "election_id": config.election_id,
            "booth_id": config.booth_id,
            "candidates": [
                {"index": c.index, "candidate_id": c.candidate_id}
                for c in config.candidates
            ],
            "trustees": {"n": config.trustees_n, "t": config.trustees_t},
            "authorities": {"agents": config.agents, "k": config.agent_k},
            "test_rate": {"num": config.test_rate_num, "den": config.test_rate_den},
            "ballots_expected": config.ballots_expected,
        }
        self.board["base_hash"] = self.Q.hex()
        self.board["trustee_setup"] = {
            "n": config.trustees_n,
            "t": config.trustees_t,
            "pk": hex384(self.trustee_setup.pk),
            "commitments": [
                {"trustee_index": j,
                 "commitment": hex384(self.trustee_setup.commitments[j])}
                for j in sorted(self.trustee_setup.commitments)
            ],
        }
        self.board["authority_keys"] = self.authority_keys

        # ---- pre-poll randomness (must exist before A5 casts anything)
        try:
            self._prepare_pre_poll()
        except Exception:                                    # noqa: BLE001
            # A pre-poll failure must not crash __init__ in the UI kiosk;
            # scripts and tests can still inspect the empty state.
            pass

    # ------------------------------------------------------------------
    # Pre-poll (A7b): draw r vectors for every serial + schedule seed
    # ------------------------------------------------------------------

    def _prepare_pre_poll(self) -> None:
        """Draw randomness vectors and the test-schedule seed.

        Deterministic on ``self.config.seed`` for replay.

        For each serial in [1, ballots_expected]:

            r_i uniform in [1, q)    (SPEC section 7 / handbook A7b)
            nonce = 32 random bytes
            K_s = SHA-256(L("EVOTE-RCOMMIT-v1") || Q || S32(booth_id)
                          || U64(serial) || I2B(r_1) || ... || I2B(r_m)
                          || nonce)                        (SPEC 10.1)

        The schedule seed is a 32-byte value drawn from the same RNG and
        committed as T of SPEC 10.2. Serial s is a test ballot iff the
        SPEC 10.2 per-serial draw selects it.
        """
        ballots = int(self.config.ballots_expected)
        m = self.config.candidate_count
        rng = random.Random(int(self.config.seed))

        booth_bytes = S32(self.config.booth_id)

        for s in range(1, ballots + 1):
            r_int: List[int] = []
            r_hex: List[str] = []
            for _ in range(m):
                # r in [1, q) - SPEC section 7. B's encrypt_and_prove
                # rejects r == 0 explicitly.
                r = 1 + rng.randrange(q_ord - 1)
                r_int.append(r)
                r_hex.append(I2B(r).hex())

            nonce_raw = rng.randbytes(32)
            if all(b == 0 for b in nonce_raw):
                nonce_raw = b"\x01" + rng.randbytes(31)
            nonce_hex = nonce_raw.hex()

            digest = hashlib.sha256()
            digest.update(L("EVOTE-RCOMMIT-v1"))
            digest.update(self.Q)
            digest.update(booth_bytes)
            digest.update(s.to_bytes(8, "big"))
            for r in r_int:
                digest.update(I2B(r))
            digest.update(nonce_raw)
            commitment = digest.hexdigest()

            self._r_int[s] = r_int
            self.pre_poll_randomness[s] = r_hex
            self.pre_poll_nonces[s] = nonce_hex
            self.pre_poll_commitments[s] = commitment

        # Schedule seed and its commitment (SPEC section 10.2).
        sched = rng.randbytes(32)
        if all(b == 0 for b in sched):
            sched = b"\x01" + rng.randbytes(31)
        # NOTE: schedule seed is SECRET until poll close.
        self._schedule_seed_raw: bytes = sched
        num, den = self.config.test_rate_num, self.config.test_rate_den
        self.schedule_commitment = hashlib.sha256(
            L("EVOTE-TESTSCHED-v1") + self.Q + booth_bytes + sched
            + num.to_bytes(8, "big") + den.to_bytes(8, "big")
        ).hexdigest()

        # Derive the test schedule (SPEC 10.2).
        self.scheduled_tests = _derive_schedule(
            seed=sched,
            ballots_expected=ballots,
            num=num,
            den=den,
        )

    # ------------------------------------------------------------------
    # A5: encrypt + prove
    # ------------------------------------------------------------------

    def encrypt_and_prove(self, candidate_index: int) -> BallotArtifacts:
        """Run the real Basket B pipeline for the current session's ballot.

        Attack hook A8 (vote redirection) is applied here: the substituted
        index is what actually gets encrypted, and the true selection is
        recorded in the private log only.

        The randomness vector, nonce and serial come from the pre-poll
        commitments; nothing is redrawn.
        """
        session = self.poll_state.current_ballot
        serial = session.serial if session else self.poll_state.next_serial

        substituted_index = candidate_index
        if self.attack_config.vote_redirection_enabled:
            substituted_index = self.attack_config.redirect_to_index
            self.private_log.log_redirection(
                candidate_index, substituted_index, serial
            )

        artifacts = self._build_artifacts_for_serial(serial, substituted_index)
        self.last_artifacts = artifacts
        return artifacts

    def _build_artifacts_for_serial(
        self, serial: int, candidate_index: int,
    ) -> BallotArtifacts:
        """Build artifacts for a specific serial + candidate.

        Also used by ``challenge_serial`` when the tester spoils a serial
        that never went through the UI flow.
        """
        m = self.config.candidate_count

        if serial in self._r_int:
            r_int = list(self._r_int[serial])
            r_hex = list(self.pre_poll_randomness[serial])
            nonce_hex = self.pre_poll_nonces[serial]
        else:
            # Extreme fallback (unregistered serial). Draw ints in [1, q)
            # with `secrets`, not `random`, since we are outside the
            # deterministic pre-poll window.
            r_int = [1 + secrets.randbelow(q_ord - 1) for _ in range(m)]
            r_hex = [I2B(r).hex() for r in r_int]
            nonce_hex = secrets.token_hex(32)

        # Deterministic per-ballot RNG for the proof randomness (w, c_d,
        # f_d). Fed into Basket B; seeded from (config.seed, serial) so
        # tests can reproduce a specific ballot.
        proof_rng = random.Random((int(self.config.seed) << 32) ^ (serial * 2654435761 & 0xFFFFFFFF))

        t0 = time.perf_counter()
        cts, vps, sp = b_encrypt_and_prove(
            candidate_index=candidate_index,
            r_vector=r_int,
            Q=self.Q,
            booth_id=self.config.booth_id,
            ballot_serial=serial,
            pk=self.trustee_setup.pk,
            m=m,
            rng=proof_rng,
        )
        encryption_ms = (time.perf_counter() - t0) * 1000.0

        t1 = time.perf_counter()
        # Build the SPEC section 14 record (which also validates its own
        # shape and every HEX384 field width).
        record = build_ballot_record(
            booth_id=self.config.booth_id,
            ballot_serial=serial,
            m=m,
            ciphertexts=cts,
            validity_proofs=vps,
            sum_proof=sp,
        )
        cast_ms = (time.perf_counter() - t1) * 1000.0

        artifacts = BallotArtifacts(
            serial=serial,
            candidate_index=candidate_index,
            ciphertexts=record["ciphertexts"],
            validity_proofs=record["validity_proofs"],
            sum_proof=record["sum_proof"],
            randomness=r_hex,
            nonce=nonce_hex,
            encryption_ms=encryption_ms,
            cast_ms=cast_ms,
        )
        # DEBUG-ONLY: track what was encrypted per serial for the
        # DEBUG-ONLY: track what was encrypted per serial for the
        # ``board_records`` view (not the exported board).
        self._encrypted_index_by_serial[serial] = candidate_index

        # B12 malformed ballot injection ------------------------------
        # If the operator has enabled B12, mutate the just-built
        # artifacts before they hit the board. Three flavours:
        #   - outside_range: flip one hex nibble in the first
        #     validity proof's c0 -> c0+c1 no longer sums to the
        #     Fiat-Shamir challenge. D catches at P2.
        #   - two_ones: replace the sum proof with one that would only
        #     verify if the ballot encoded two 1's. D catches at P2.
        #   - non_canonical: replace one alpha with alpha + p (which
        #     reduces to the same group element but is a non-canonical
        #     representation). D catches at subgroup upper-bound.
        if self.attack_config.malformed_ballot_enabled:
            variant = self.attack_config.malformed_ballot_variant
            if variant == "outside_range":
                vp0 = dict(artifacts.validity_proofs[0])
                c0 = vp0["c0"]
                vp0["c0"] = ("f" if c0[0] != "f" else "0") + c0[1:]
                artifacts.validity_proofs[0] = vp0
            elif variant == "two_ones":
                sp = dict(artifacts.sum_proof)
                r = sp["r"]
                sp["r"] = ("f" if r[0] != "f" else "0") + r[1:]
                artifacts.sum_proof = sp
            elif variant == "non_canonical":
                ct0 = dict(artifacts.ciphertexts[0])
                alpha_int = int(ct0["alpha"], 16)
                non_canonical = alpha_int + p_mod
                ct0["alpha"] = format(non_canonical, "0768x")
                artifacts.ciphertexts[0] = ct0

        return artifacts

    # ------------------------------------------------------------------
    # Board append (delegates to Basket C's board.board)
    # ------------------------------------------------------------------

    def append_ballot(self, artifacts: BallotArtifacts) -> None:
        """Append a normal ballot record to the bulletin board.

        Also fires the A9 ballot-stuffing hook if enabled. Stuffed ballots
        are appended as complete SPEC section 14 ballot records
        (encrypted, proofs and all) so they pass the shape checker and
        can only be caught by the poll-register mismatch of A6.
        """
        record = {
            "record_type": "ballot",
            "booth_id": self.config.booth_id,
            "ballot_serial": artifacts.serial,
            "ciphertexts": artifacts.ciphertexts,
            "validity_proofs": artifacts.validity_proofs,
            "sum_proof": artifacts.sum_proof,
        }
        bb.append_ballot(self.board, record)

        if (
            self.attack_config.ballot_stuffing_enabled
            and not self._stuffing_done
            and self.attack_config.stuffed_count > 0
        ):
            self._stuff_ballots(self.attack_config.stuffed_count)
            self._stuffing_done = True

    def _stuff_ballots(self, count: int) -> None:
        base_serial = 1_000_000
        m = self.config.candidate_count
        for offset in range(count):
            stuffed_serial = base_serial + offset
            # Draw one-off r vector (never committed pre-poll - this
            # is what makes the ballot stuffing catchable by the
            # register / spoil audit).
            r_int = [1 + secrets.randbelow(q_ord - 1) for _ in range(m)]
            proof_rng = random.Random(0xB000 + offset)
            cts, vps, sp = b_encrypt_and_prove(
                candidate_index=0,
                r_vector=r_int,
                Q=self.Q,
                booth_id=self.config.booth_id,
                ballot_serial=stuffed_serial,
                pk=self.trustee_setup.pk,
                m=m,
                rng=proof_rng,
            )
            rec = build_ballot_record(
                booth_id=self.config.booth_id,
                ballot_serial=stuffed_serial,
                m=m,
                ciphertexts=cts,
                validity_proofs=vps,
                sum_proof=sp,
            )
            bb.append_ballot(self.board, rec)
        self.private_log.log_stuffing(count)

    def append_spoil(
        self, artifacts: BallotArtifacts, opened_index: int,
    ) -> None:
        """A7 spoil flow.

        Ballot record has already been (or is now) appended. The spoil
        record reveals the randomness vector and the opened candidate
        index; the ballot is excluded from the tally (see
        ``valid_ballots`` and ``tally.aggregate_valid_ballots``).
        """
        # First make sure the ballot itself is on the board. If the
        # admin spoils immediately after a cast the ballot was already
        # appended by cast_vote(); if the tester spoils a scheduled test
        # serial that never went through the UI it will not be.
        existing_serials = {
            b["ballot_serial"] for b in self.board.get("ballots", [])
        }
        if artifacts.serial not in existing_serials:
            ballot_record = {
                "record_type": "ballot",
                "booth_id": self.config.booth_id,
                "ballot_serial": artifacts.serial,
                "ciphertexts": artifacts.ciphertexts,
                "validity_proofs": artifacts.validity_proofs,
                "sum_proof": artifacts.sum_proof,
            }
            bb.append_ballot(self.board, ballot_record)

        spoil_record = {
            "record_type": "spoil",
            "booth_id": self.config.booth_id,
            "ballot_serial": artifacts.serial,
            "opened_candidate_index": opened_index,
            "randomness": artifacts.randomness,
            "nonce": artifacts.nonce,
        }
        bb.append_spoil(self.board, spoil_record)

    def verify_spoil_record(self, spoil_record: Dict[str, Any]) -> bool:
        """SPEC section 11 sanity check.

        Re-encrypt the opened candidate index with the revealed
        randomness and compare byte-for-byte against the ciphertexts
        published in the corresponding ballot record. Any mismatch
        fails the whole record.
        """
        serial = spoil_record.get("ballot_serial")
        opened = spoil_record.get("opened_candidate_index")
        r_hex = spoil_record.get("randomness", [])
        if not isinstance(serial, int) or not isinstance(opened, int):
            return False
        if len(r_hex) != self.config.candidate_count:
            return False

        ballot = next(
            (b for b in self.board.get("ballots", [])
             if b.get("ballot_serial") == serial),
            None,
        )
        if ballot is None:
            return False

        r_int = [int(h, 16) for h in r_hex]
        # Re-encrypt with the revealed r vector.
        cts, _ = encrypt_selection(
            self.trustee_setup.pk,
            self.config.candidate_count,
            opened,
            randomness=r_int,
        )
        pub_cts = ballot.get("ciphertexts", [])
        if len(pub_cts) != len(cts):
            return False
        for i, pub in enumerate(pub_cts):
            if pub["alpha"] != hex384(cts[i].alpha):
                return False
            if pub["beta"] != hex384(cts[i].beta):
                return False
        return True

    def challenge_serial(
        self, serial: int, opened_index: int,
    ) -> Dict[str, Any]:
        """Full challenge flow for a serial that may or may not have
        gone through the UI.

        Builds a full ballot from the committed pre-poll randomness,
        appends the ballot + spoil records, runs the SPEC section 11
        sanity check and stamps ``verified`` on the spoil record.
        """
        artifacts = self._build_artifacts_for_serial(serial, opened_index)
        self.append_spoil(artifacts, opened_index)
        spoil_record = next(
            (r for r in reversed(self.board.get("spoils", []))
             if r.get("ballot_serial") == serial),
            None,
        )
        if spoil_record is None:
            raise RuntimeError("failed to append spoil record")
        spoil_record["verified"] = self.verify_spoil_record(spoil_record)
        return spoil_record

    # ------------------------------------------------------------------
    # Pre-poll section publication (before poll opens)
    # ------------------------------------------------------------------

    def publish_pre_poll_commitments(self) -> None:
        """Publish per-serial randomness commitments + test schedule commit.

        Handbook Section 4.3, C6b: *"Ingest A's randomness commitments
        and test schedule commitment into the board before the poll
        opens, and the revealed schedule seed at close."*
        """
        commits = []
        for s in range(1, int(self.config.ballots_expected) + 1):
            commit = self.pre_poll_commitments.get(s)
            if commit is None:
                continue
            # The nonce stays secret until the serial is spoiled (SPEC
            # 10.1, handbook C9); only K_s is published.
            commits.append({
                "ballot_serial": s,
                "commitment": commit,
            })
        bb.append_prepoll(
            self.board,
            randomness_commitments=commits,
            test_schedule_commitment=self.schedule_commitment or "",
        )

    def reveal_schedule_and_publish_register(self) -> None:
        """Reveal the schedule seed at close and publish the poll register.

        SPEC section 10.2 (schedule opening) + SPEC section 12 (poll
        register).
        """
        if self.schedule_commitment is not None and hasattr(
            self, "_schedule_seed_raw"
        ):
            self.schedule_seed = self._schedule_seed_raw.hex()
            bb.append_schedule_opening(self.board, self.schedule_seed)
        self.append_register()

    def append_register(self) -> None:
        """A6 poll register: (issued, spoiled, counted). Written via C."""
        reg = self.poll_state.poll_register()
        bb.write_poll_register(
            self.board,
            issued=reg["ballots_issued"],
            spoiled=reg["ballots_spoiled"],
            counted=reg["ballots_counted"],
            booth_id=self.config.booth_id,
        )

