@dataclass
class BallotArtifacts:
    """A completed ballot in the shape the admin UI expects.

    Fields:

    * ``serial``           - integer ballot serial (>=1)
    * ``candidate_index``  - candidate actually encrypted (may differ from
      the voter's true selection if the vote-redirection attack (A8) is on)
    * ``ciphertexts``      - list of dicts ``{candidate_index, alpha, beta}``
      with ``alpha`` and ``beta`` as HEX384 strings (SPEC section 14 shape)
    * ``validity_proofs``  - list of dicts, SPEC section 14 shape
    * ``sum_proof``        - dict, SPEC section 14 shape
    * ``randomness``       - list of HEX384 strings for admin display and
      for the spoil record (SPEC section 11)
    * ``nonce``            - 32-byte hex commitment nonce
    * ``encryption_ms``    - encryption timing (feeds A10 features and A11
      benchmarks)
    * ``cast_ms``          - proof timing
    """

    serial: int
    candidate_index: int
    ciphertexts: List[Dict[str, Any]]
    validity_proofs: List[Dict[str, Any]]
    sum_proof: Dict[str, Any]
    randomness: List[str]
    nonce: str
    encryption_ms: float
    cast_ms: float


@dataclass
class AttackConfig:
    """Attack-hook toggles owned by A + B + C.

    A8 vote redirection, A9 ballot stuffing (Basket A).
    B12 malformed ballot injection (Basket B).
    C10 tally manipulation, C11 retroactive board edit (Basket C).
    """
    # A8
    vote_redirection_enabled: bool = False
    redirect_to_index: int = 0
    # A9
    ballot_stuffing_enabled: bool = False
    stuffed_count: int = 0
    # B12
    malformed_ballot_enabled: bool = False
    malformed_ballot_variant: str = "outside_range"    # or "two_ones", "non_canonical"
    # C10
    tally_manipulation_enabled: bool = False
    # C11
    retroactive_board_edit_enabled: bool = False


@dataclass
class PrivateAttackLog:
    """The private log the verifier must never see (handbook A8).

    Filtered out of any exported bulletin board by ``board.export.scan_for_secrets``
    which rejects the key ``private_log`` outright, so the log stays in
    memory only.
    """
    entries: List[Dict[str, Any]] = field(default_factory=list)

    def log_redirection(self, true_index: int, substituted_index: int, serial: int) -> None:
        self.entries.append({
            "type": "vote_redirection",
            "ballot_serial": serial,
            "true_selection": true_index,
            "substituted_selection": substituted_index,
        })

    def log_stuffing(self, count: int) -> None:
        self.entries.append({"type": "ballot_stuffing", "stuffed_ballots": count})


