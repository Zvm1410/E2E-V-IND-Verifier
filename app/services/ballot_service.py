"""Ballot processing (A5, A7, A8, A9), integrated with real Basket B and C.

INTEGRATION NOTES
-----------------
The pre-integration version of this file contained a stub implementation of
``encrypt_and_prove`` that returned ``_fake_hex384(seed)`` values (SHA-256
tiled to 768 hex chars) and hand-rolled board dicts. Both are removed in
the integrated build:

* Encryption / proof generation now calls
  ``crypto.encrypt_and_prove.encrypt_and_prove`` from Basket B, which
  returns real (alpha, beta) ciphertexts, real Cramer-Damgard-Schoenmakers
  OR-proofs and a real Chaum-Pedersen sum-to-one proof.
* Ballot record shape is built by ``crypto.record.build_ballot_record``,
  the canonical SPEC section 14 record.
* Bulletin-board writes go through ``board.board`` (from Basket C).

The public interface that the PyQt UI consumes is unchanged:
``BallotService(config, poll_state)``,
``BallotService.encrypt_and_prove(candidate_index) -> BallotArtifacts``,
``append_ballot(artifacts)``, ``append_spoil(artifacts, opened_index)``,
``challenge_serial(serial, opened_index)``, ``append_register()``,
``publish_pre_poll_commitments()``, ``reveal_schedule_and_publish_register()``,
``export_board(filename)``, ``build_receipt_code(artifacts)``.

The ``BallotArtifacts`` dataclass keeps its old field names too, so the
admin screen's diagnostic dump keeps rendering. What changed inside:

* ``randomness`` is still a list of hex strings for display, but the
  underlying integers used by Basket B are stored in a private list
  ``_r_int`` inside the service, keyed by serial. Basket B rejects
  hex strings for ``r_vector``; SPEC section 7 says ``r`` lives in
  ``[1, q)`` and B's ``encrypt_and_prove`` asserts this.
* Pre-poll randomness is now generated by drawing ``r`` uniformly
  from ``[1, q)`` with ``random.Random(config.seed)``. The commitment
  is SHA-256 over ``I2B(serial, 8) || S32(booth_id) || I2B(r_1) || ...
  || I2B(r_m) || nonce``, matching the SPEC section 10.1 preimage
  structure closely enough that the verifier can recompute it.

Ownership discipline (per handbook Task 4.1): this module wires A -> B
-> C. It does not implement cryptography. Every arithmetic operation
comes from Basket B or Basket C.
"""

